"use client";

import { useState } from "react";

type Axis = {
  axis_id: string;
  description: string;
  size: number;
  share_of_failures: number;
  jaccard: Record<string, number>;
  precision: Record<string, number>;
};

type EvaluationRun = {
  run: string;
  layer: number;
  rollouts: number;
  failing: number;
  contrastive_axes: Axis[];
  contrastive_capped_axes: Axis[];
};

type EvaluationFile = {
  gaps: Record<string, number>;
  runs: EvaluationRun[];
};

export default function AxisImporter() {
  const [data, setData] = useState<EvaluationFile | null>(null);
  const [error, setError] = useState("");
  const [selectedRun, setSelectedRun] = useState(0);
  const [variant, setVariant] = useState<"contrastive_axes" | "contrastive_capped_axes">(
    "contrastive_axes"
  );

  async function handleUpload(file?: File) {
    if (!file) return;

    try {
      const parsed: unknown = JSON.parse(await file.text());

      if (
        !parsed ||
        typeof parsed !== "object" ||
        !("runs" in parsed) ||
        !Array.isArray(parsed.runs)
      ) {
        throw new Error("Invalid evaluation file: missing runs array.");
      }

      const evaluation = parsed as EvaluationFile;

      if (
        evaluation.runs.some(
          (run) =>
            !Array.isArray(run.contrastive_axes) ||
            !Array.isArray(run.contrastive_capped_axes)
        )
      ) {
        throw new Error("Invalid evaluation file: missing axis arrays.");
      }

      setData(evaluation);
      setSelectedRun(0);
      setError("");
    } catch (err) {
      setData(null);
      setError(err instanceof Error ? err.message : "Unable to read file.");
    }
  }

  const run = data?.runs[selectedRun];
  const axes = run?.[variant] ?? [];

  return (
    <section className="mt-10 rounded-xl border border-gray-200 bg-white p-6">
      <h2 className="text-xl font-semibold">Discovered Failure Axes</h2>

      <p className="mt-2 text-sm text-gray-500">
        Import a JSON report generated by src/discovery/dev_eval.py.
        Files are processed locally in your browser.
      </p>

      <input
        type="file"
        accept=".json,application/json"
        onChange={(event) => handleUpload(event.target.files?.[0])}
        className="mt-5 block w-full text-sm"
      />

      {error && (
        <p role="alert" className="mt-4 text-sm text-red-600">
          {error}
        </p>
      )}

      {!data && !error && (
        <p className="mt-6 rounded-lg bg-gray-50 p-5 text-sm text-gray-500">
          No discovery evaluation loaded. Upload a report to explore actual
          failure axes.
        </p>
      )}

      {data && (
        <>
          <div className="mt-6 flex flex-wrap gap-4">
            <label className="text-sm">
              Evaluation run
              <select
                value={selectedRun}
                onChange={(event) => setSelectedRun(Number(event.target.value))}
                className="mt-2 block rounded-lg border px-3 py-2"
              >
                {data.runs.map((item, index) => (
                  <option key={index} value={index}>
                    {item.run} (layer {item.layer})
                  </option>
                ))}
              </select>
            </label>

            <label className="text-sm">
              Discovery variant
              <select
                value={variant}
                onChange={(event) =>
                  setVariant(
                    event.target.value as
                      | "contrastive_axes"
                      | "contrastive_capped_axes"
                  )
                }
                className="mt-2 block rounded-lg border px-3 py-2"
              >
                <option value="contrastive_axes">Contrastive</option>
                <option value="contrastive_capped_axes">
                  Contrastive (capped)
                </option>
              </select>
            </label>
          </div>

          {run && (
            <p className="mt-4 text-sm text-gray-500">
              {run.rollouts} rollouts · {run.failing} failures · {axes.length} axes
            </p>
          )}

          <div className="mt-6 overflow-x-auto">
            <table className="w-full text-left text-sm">
              <thead className="border-b bg-gray-50 text-gray-600">
                <tr>
                  <th className="p-3">Axis</th>
                  <th className="p-3">Associated rollouts</th>
                  <th className="p-3">Share of failures</th>
                  <th className="p-3">Gap overlap (Jaccard)</th>
                </tr>
              </thead>

              <tbody>
                {axes.map((axis) => (
                  <tr key={axis.axis_id} className="border-b">
                    <td className="p-3">
                      <p className="font-medium">{axis.axis_id}</p>
                      <p className="mt-1 text-gray-500">{axis.description}</p>
                    </td>
                    <td className="p-3">{axis.size}</td>
                    <td className="p-3">
                      {(axis.share_of_failures * 100).toFixed(1)}%
                    </td>
                    <td className="p-3">
                      {Object.entries(axis.jaccard)
                        .map(([gap, value]) => `${gap}: ${value.toFixed(3)}`)
                        .join(" · ") || "—"}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>

            {axes.length === 0 && (
              <p className="py-8 text-center text-gray-500">
                No axes were produced for this run and variant.
              </p>
            )}
          </div>
        </>
      )}
    </section>
  );
}
"use client";

import { useRef, useState } from "react";
import { parseEvaluationReport, type EvaluationReport } from "./evaluation-report";

export default function AxisImporter() {
  const [data, setData] = useState<EvaluationReport | null>(null);
  const [error, setError] = useState("");
  const [selectedMethod, setSelectedMethod] = useState("");
  const uploadVersion = useRef(0);

  async function handleUpload(file?: File) {
    if (!file) return;
    const version = ++uploadVersion.current;
    setData(null);
    setError("");
    try {
      const report = parseEvaluationReport(JSON.parse(await file.text()));
      // A slower previous upload must not replace the most recently selected file.
      if (version !== uploadVersion.current) return;
      setData(report);
      setSelectedMethod(Object.keys(report.methods)[0] ?? "");
    } catch (err) {
      if (version !== uploadVersion.current) return;
      setError(err instanceof Error ? err.message : "Unable to read file.");
    }
  }

  const method = data?.methods[selectedMethod];
  const gaps = Object.entries(method?.gaps ?? {});

  return (
    <section className="mt-10 rounded-xl border border-gray-200 bg-white p-6">
      <h2 className="text-xl font-semibold">Imported Development Evaluation</h2>
      <p className="mt-2 text-sm text-gray-500">
        Import a JSON report generated by src/discovery/dev_eval.py.
        Files are processed locally in your browser. Development results are
        exploratory: the best axis for each gap is selected using the answer key.
        Reports contain gap summaries, not the complete list of discovered axes.
        Recovery indicates whether any axis meets the report’s recovery rule;
        it need not be the best-overlap axis shown.
      </p>
      <label className="mt-5 block text-sm">
        Development evaluation JSON
        <input type="file" accept=".json,application/json"
          onChange={(event) => handleUpload(event.target.files?.[0])}
          className="mt-2 block w-full text-sm" />
      </label>
      {error && <p role="alert" className="mt-4 text-sm text-red-600">{error}</p>}
      {!data && !error && (
        <p className="mt-6 text-sm text-gray-500">No evaluation loaded. Select a development report to inspect its methods.</p>
      )}
      {data && (
        <>
          <p className="mt-4 text-sm text-gray-500">
            Layer {data.layer} · {data.corpus.rollouts} rollouts · {data.corpus.failures} failures
          </p>
          {Object.keys(data.methods).length === 0 ? (
            <p className="mt-4 text-sm text-gray-500">This report contains no methods.</p>
          ) : (
            <label className="mt-5 block text-sm">
              Evaluation method and run
              <select value={selectedMethod} onChange={(event) => setSelectedMethod(event.target.value)}
                className="mt-2 block max-w-full rounded-lg border px-3 py-2">
                {Object.entries(data.methods).map(([label, item]) => (
                  <option key={label} value={label}>{label}{item.counts ? "" : " (excluded)"}</option>
                ))}
              </select>
            </label>
          )}
          {method && (
            <>
              <p className="mt-4 text-sm text-gray-500">
                {method.family} · {method.kind} · {method.score.n_axes} axes emitted
              </p>
              {!method.counts && <p role="status" className="mt-3 text-sm text-amber-800">
                This method/run does not count toward the evaluation rule. Its scores are shown for inspection only.
              </p>}
              <div className="mt-6 overflow-x-auto">
                <table className="w-full text-left text-sm">
                  <caption className="pb-3 text-left text-gray-500">Best axis per gap (chosen using the key)</caption>
                  <thead className="border-b bg-gray-50 text-gray-600"><tr>
                    {["Gap", "Best axis", "Associated rollouts", "Share of failures", "Jaccard", "Recovers gap"].map((title) =>
                      <th key={title} scope="col" className="p-3">{title}</th>)}
                  </tr></thead>
                  <tbody>{gaps.map(([gap, row]) => (
                    <tr key={gap} className="border-b">
                      <td className="p-3">{gap}</td>
                      <td className="p-3">{row.axis_id ?? "No axis"}</td>
                      <td className="p-3">{row.axis_size}</td>
                      <td className="p-3">{(row.share_of_failures * 100).toFixed(1)}%</td>
                      <td className="p-3">{row.best_jaccard.toFixed(3)}</td>
                      <td className="p-3">{row.recovers ? "Yes" : "No"}</td>
                    </tr>
                  ))}</tbody>
                </table>
                {gaps.length === 0 && <p className="py-6 text-gray-500">No gap summaries for this method.</p>}
              </div>
            </>
          )}
        </>
      )}
    </section>
  );
}
